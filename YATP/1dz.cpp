//Сейчас рейтинг фильма равен X (рейтинг — средняя оценка, округлённая до десятых по математическим правилам, цифра 5 всегда округляется вверх). 
//Сколько минимум раз нужно поставить фильму оценку 1, чтобы его рейтинг гарантированно стал не выше Y? В решении нельзя использовать циклы.



// Х от 1 до 10
// Рейтинг (оценка+оценка+...+оценка) / на кол-во оценок и округленное до десятых(x.y)
// Y от 1 до 10

// если Y >= X по вводу то сразу выводим 0 оценок,
// если Y < X то заменяем переменную рейтинга добавляя "туда" единичку, и используем счетчик С

// x y n
//9.8 4.9 80 --> 99
//2 1 2 --> 39
//6 7 8 --> 0

#include <iostream>
#include <cmath>
using namespace std;

int main() {
    float x,y,n;
    std::cin >> x >> y >> n;
    double rnx = std::round(x*10.0) / 10.0; // это получается (сумма звезд) / n (изначальная)
    double rny = std::round(y*10.0) / 10.0; 

    int k;

    if (rny >= rnx) {
        cout << 0;
        return 0;
    }
    else {
        k = ((n * (rnx * 100 - rny * 100 - 5)) / (rny * 100 - 95)) + 1;
        cout << k;
        return 0;
    }
}